const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const context=vm.createContext({console,document:{addEventListener(){}},setTimeout,clearTimeout});
vm.runInContext(fs.readFileSync('dist/base_projects.js','utf8'),context);
vm.runInContext(fs.readFileSync('dist/seed.js','utf8'),context);
vm.runInContext(fs.readFileSync('dist/app.js','utf8').replace(/init\(\);\s*$/,''),context);
vm.runInContext(`state.sources=${fs.readFileSync('dist/sources.json','utf8')}`,context);
const run=s=>vm.runInContext(s,context);
assert.equal(run('validateWorkspace(state)'),true);
assert.equal(run('state.tasks.length'),49);
assert.equal(run('leaves().length'),41);
assert.equal(run('computeSchedule().unresolved.length'),0);
assert.equal(run('Object.keys(computeSchedule().items).length'),41);
assert.ok(run('computeSchedule().max')>20);
for(const view of ['tree','board','streams','coverage','timeline','sources']){
 run(`state.view='${view}'`);
 const html=run('viewHtml()');
 assert.ok(html.length>500,`${view} should render meaningful content`);
 assert.ok(!html.includes('undefined'),`${view} should not include undefined`);
}
run(`state.filters.video='005'`);
assert.ok(run(`leaves().filter(matches).every(t=>t.videos.includes('005'))`));
assert.ok(run(`leaves().filter(matches).length`)>5);
run(`state.filters=clone(DEFAULT_STATE.filters);state.filters.query='simulator'`);
assert.ok(run('leaves().filter(matches).length')>=2);
run(`state.filters=clone(DEFAULT_STATE.filters);state.filters.discipline='Art'`);
assert.ok(run(`leaves().filter(matches).every(t=>t.discipline==='Art')`));
run(`state.filters=clone(DEFAULT_STATE.filters)`);
const draft=run(`extractDraft(${JSON.stringify('# Camera\n- Setup camera for videos 005–006\n- Design industrial steering wheel\n- Design industrial steering wheel')},'Test import')`);
assert.equal(draft.items.length,2);
assert.deepEqual(Array.from(draft.items[0].videos),['005','006']);
assert.equal(draft.items[1].discipline,'Art');
assert.equal(draft.items[0].section,'Camera');
assert.ok(run(`esc('<script>"&')`)==='&lt;script&gt;&quot;&amp;');
run(`taskById('002').title='<img src=x onerror=alert(1)>'`);
assert.ok(run(`treeHtml().includes('&lt;img')`));
run(`taskById('002').title='Setup map for videos 001, 002, 005, 006'`);
run(`taskById('002').dependencies=['006']`);
assert.throws(()=>run('validateWorkspace(state)'),/cycle/);
run(`taskById('002').dependencies=[]`);
assert.equal(run('validateWorkspace(state)'),true);
run(`const child=newTaskObject('Nested task','002','Art',['001'],['map']);state.tasks.push(child)`);
assert.equal(run(`children('002').length`),1);
assert.equal(run(`leaves().some(t=>t.id==='002')`),false);
assert.equal(run('computeSchedule().unresolved.length'),0);
assert.equal(run('validateWorkspace(state)'),true);
assert.ok(run(`treeHtml().includes('Nested task')`));
run(`taskById('002').parent=child.id`);
assert.throws(()=>run('validateWorkspace(state)'),/cycle/);
console.log('PASS: 49 seed records, 41 leaf tasks, all six views, dependency schedule, filters, draft extraction, escaping, nested subtasks and invalid-workspace rejection.');
