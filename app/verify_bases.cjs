const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const elements=new Map();
const context=vm.createContext({console,document:{body:{style:{}},addEventListener(){},getElementById(id){if(!elements.has(id))elements.set(id,{innerHTML:'',focus(){}});return elements.get(id);},querySelectorAll(){return[];},querySelector(){return null;}},setTimeout,clearTimeout});
for(const file of ['dist/base_projects.js','dist/seed.js'])vm.runInContext(fs.readFileSync(file,'utf8'),context);
vm.runInContext(fs.readFileSync('dist/app.js','utf8').replace(/init\(\);\s*$/,''),context);
const run=s=>vm.runInContext(s,context);
run(`state.sources=${fs.readFileSync('dist/sources.json','utf8')}`);
assert.equal(run('validateWorkspace(state)'),true);
assert.equal(run('rankBaseProjects()[0].name'),'Creative Pyramid');
assert.equal(run('rankBaseProjects()[0].count'),4);
assert.equal(run(`rankBaseProjects().find(p=>p.id==='korean-trash').count`),3);
assert.equal(run(`rankBaseProjects().find(p=>p.id==='coin-pusher').count`),3);
assert.ok(run(`rankBaseProjects()[0].aliases.includes('Video 304')`));
assert.ok(run(`!rankBaseProjects().some(p=>/^Video 00[1-8]$/.test(p.name))`));
run(`state.baseProjects.push(clone(state.baseProjects[0]));`);
assert.equal(run('rankBaseProjects()[0].count'),4);
run(`state.baseProjects.push({id:'alias-pyramid',name:'Video 304',aliases:[],scope:'seed',brief:'2F Crusher Factory',references:clone(state.baseProjects[0].references)});`);
assert.equal(run(`rankBaseProjects().filter(p=>p.aliases.includes('Video 304')).length`),1);
assert.equal(run('rankBaseProjects()[0].count'),4);
run(`state.baseProjects.push({id:'fake',name:'Unverified project',aliases:[],scope:'seed',references:[{requirement:'Map',category:'Map',use_type:'Reuse',source_id:'map',quote:'This source text does not exist.'}]});`);
assert.ok(run(`!rankBaseProjects().some(p=>p.id==='fake')`));
run(`state.baseSelections={seed:'coin-pusher'};`);
assert.equal(run('baseChoice().candidate.id'),'coin-pusher');
assert.equal(run('baseChoice().manual'),true);
const exported=JSON.parse(run('JSON.stringify(state)'));
assert.equal(exported.baseSelections.seed,'coin-pusher');
run(`state.view='bases';render();`);
const baseHtml=elements.get('app').innerHTML;
assert.ok(baseHtml.includes('Base project'));
assert.ok(baseHtml.includes('4 supporting requirements'));
assert.ok(baseHtml.includes('Use as base'));
assert.ok(!baseHtml.includes('id="filter-status"'));
run('state.view="tree";render();');
assert.ok(!elements.get('app').innerHTML.includes('One brief. Eight videos.'));
assert.ok(elements.get('app').innerHTML.includes('Suggested base')===false); // manual choice
run(`detailModal('002')`);
const detail=elements.get('overlay').innerHTML;
assert.ok(detail.includes('<details class="task-more">'));
for(const id of ['f-title','f-status','f-discipline','f-owner','f-estimate','f-priority','f-deps','f-description','f-criteria','f-notes'])assert.ok(detail.includes(`id="${id}"`),id+' remains editable');
assert.ok(!detail.includes('Task scope and completion criteria are planning suggestions'));
// Explicit alias bridges merge all candidates, not just the first match.
run(String.raw`const source=state.sources[0];source.text+='\nReuse rail from A. Reuse map from B.';const bridge=[{id:'a',name:'A',aliases:['Video 123'],scope:'test',references:[{requirement:'Rail',category:'Gameplay',use_type:'Reuse',source_id:'references',quote:'Reuse rail from A.'}]},{id:'b',name:'B',aliases:['Video 456'],scope:'test',references:[{requirement:'Map',category:'Map',use_type:'Reference',source_id:'references',quote:'Reuse map from B.'}]},{id:'bridge',name:'Project AB',aliases:['Video 123','Video 456'],scope:'test',references:[]}];`);
assert.equal(run(`rankBaseProjects(bridge,'test').length`),1);
assert.equal(run(`rankBaseProjects(bridge,'test')[0].count`),2);
console.log('PASS: base ranking, evidence, duplicates, aliases, manual selection, export persistence, concise UI and editable collapsed details.');
